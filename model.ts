// Token Launch Radar — valuation model "comps-2".
//
// One sealed snapshot in, one ranked board out. The board covers every slug on
// the snapshot's watchlist (the floor, never the ceiling) plus every other
// pre-token protocol the radar can rank: protocols that record no token and are
// not a wrapped, staked or bridged product of a token that already trades.
// Live-token protocols are kept apart and shown at the market's own value.
//
// Implied value is built only from the snapshot's own figures, in four steps:
//
//   peer     = the category's peer multiple: the trimmed median FDV/TVL of the
//              live-token protocols in the same category, shrunk toward the
//              whole-market median (0.205) and clamped to [0.05, 1.50]
//   growth   = 1 + 0.40 * tanh(clamp(change_7d, -40, 80) / 40)   (dampened)
//   maturity = 0.65 + 0.35 * ln(1 + age/365) / ln(4), age capped at 1095 days
//   breadth  = 1 + 0.03 * min(chains - 1, 5)
//
//   implied_value_usd = round(tvl_usd * peer * growth * maturity * breadth)
//
// Age is counted from the snapshot's own as_of date, never from today, so two
// runs on the same snapshot write the same bytes. No protocol name is ever
// special-cased: the same function scores every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

